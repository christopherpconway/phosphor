#!/usr/bin/env node
// One-off: Natural Earth 110m coastlines (public domain) -> src/cockpit/coastlines.ts
// Usage: node scripts/gen-coastlines.mjs   (needs network once; output is committed)
import { writeFileSync } from "node:fs";
const FEED_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_coastline.geojson";
const gj = await (await fetch(FEED_URL)).json();
const lines = [];
for (const f of gj.features) {
  const geoms = f.geometry.type === "MultiLineString" ? f.geometry.coordinates : [f.geometry.coordinates];
  for (const g of geoms) {
    const flat = [];
    let last = "";
    for (const [lon, lat] of g) {
      const a = Math.round(lat * 10) / 10, b = Math.round(lon * 10) / 10;
      const key = `${a},${b}`;
      if (key === last) continue; // drop points that collapse at 0.1° precision
      last = key;
      flat.push(a, b);
    }
    if (flat.length >= 4) lines.push(flat);
  }
}
const body = lines.map((l) => `  [${l.join(",")}],`).join("\n");
writeFileSync(
  new URL("../src/cockpit/coastlines.ts", import.meta.url),
  `// GENERATED by scripts/gen-coastlines.mjs from Natural Earth 110m coastlines (public domain).\n` +
    `// [lat, lon, lat, lon, ...] per polyline, degrees, 0.1° precision. Do not hand-edit.\n` +
    `export const COASTLINES: readonly (readonly number[])[] = [\n${body}\n];\n`,
);
console.log(`wrote ${lines.length} polylines`);
